    /// <summary>
    /// 目标构造器选器单点（加权 + 歧义 advisory 判定）
    /// 绑定集合非空（任一候选构造器参数携带 SourcePropertyName）时，命中绑定形参名的候选
    /// 升权优先，命中集内维持"参数最多优先"机械裁决（多命中草案口径，零预演）；
    /// 命中为空走原逻辑。绑定集合为空时返回值与既有
    /// <c>Where(IsPublic).OrderByDescending(Parameters.Count).FirstOrDefault()</c> 链等价
    /// （B9 字节门——未用 MapCtorParam 的对产物零变化）。<see cref="CodeGenerator.Mapping"/>
    /// 三选器站点（Core/内联元素/init-only 变体）共用本单点（矩阵同步）。
    /// <para> advisory（机械口径）：参数数量并列第一候选 &gt;1 且绑定集合为空 → F54 Info
    /// （AddDistinct 按对去重——三站点共用不重复报）；绑定非空不报（显式绑定已表达消解意图）。</para>
    /// </summary>
    /// <param name="mapping">映射快照（绑定承载于 TargetType.Constructors 参数）</param>
    /// <param name="ctx">生成期上下文（null = 不发 advisory——兼容无上下文调用）</param>
    /// <returns>选中的公共构造器；无公共构造器为 null</returns>
    internal static ConstructorRef? SelectTargetConstructor(MappingSnapshot mapping, GenerationContext? ctx)
    {
        var ctor = SelectTargetConstructorCore(mapping, out var hasBindings, out var ambiguousTiedTop, out var tiedCount);
        if (!hasBindings && ambiguousTiedTop && ctx != null)
        {
            // Args 补第二实参（并列数量）——resx F54 消息为 2 占位符
            //（{0}=类型名、{1}=并列数量），原仅 1 实参 → GetMessage 回落裸模板（Roslyn 无异常信号）。
            ctx.Diagnostics.AddDistinct(mapping, new DiagnosticSnapshot
            {
                DescriptorId = DiagnosticDescriptorsFluent.CtorParamAmbiguousConstructorRule.Id,
                Args = new[] { mapping.TargetType.FullName, tiedCount.ToString(System.Globalization.CultureInfo.InvariantCulture) },
                Location = mapping.TargetIdentifierLocation,
            });
        }
        return ctor;
    }

    /// <summary>
    /// SelectTargetConstructor 判定内核（诊断发射与判定分离——测试侧可无 ctx 复核布尔口径）
    /// </summary>
    private static ConstructorRef? SelectTargetConstructorCore(
        MappingSnapshot mapping, out bool hasBindings, out bool ambiguousTiedTop, out int tiedCount)
    {
        hasBindings = false;
        ambiguousTiedTop = false;
        tiedCount = 0;
        var publicCtors = GetConstructors(mapping.TargetType);
        ConstructorRef? boundCtor = null;
        ConstructorRef? fallbackCtor = null;
        var tiedTop = 0;
        foreach (var c in publicCtors)
        {
            if (!c.IsPublic) continue;
            var hasBoundParam = false;
            foreach (var p in c.Parameters)
            {
                if (p.SourcePropertyName != null) { hasBoundParam = true; break; }
            }
            if (hasBoundParam)
            {
                hasBindings = true;
                // 多命中唯一化：命中者之间维持"参数最多优先"机械裁决
                //（严格大于替换——与 OrderByDescending 稳定排序 FirstOrDefault 的先出现语义同构）
                if (boundCtor == null || c.Parameters.Count > boundCtor.Parameters.Count)
                    boundCtor = c;
            }
            if (fallbackCtor == null || c.Parameters.Count > fallbackCtor.Parameters.Count)
            {
                fallbackCtor = c;
                tiedTop = 1;
            }
            else if (c.Parameters.Count == fallbackCtor.Parameters.Count)
            {
                tiedTop++;
            }
        }

        ambiguousTiedTop = tiedTop > 1;
        tiedCount = tiedTop;
        return hasBindings ? (boundCtor ?? fallbackCtor) : fallbackCtor;
    }

    /// <summary>
    /// 绑定集合非空判定（调用方门禁——Core 与内联 的
    /// hasParameterlessCtor 短路修正）。绑定非空时构造器路径优先于无参构造器分支
    /// 绑定空恒 false，
    /// 调用方谓词与现状逐字节等价（B9 字节门）。
    /// </summary>
    /// <param name="targetType">目标类型快照（绑定承载于 Constructors 参数 SourcePropertyName）</param>
    /// <returns>true = 任一公共构造器参数携带显式绑定</returns>
    internal static bool HasCtorParamBindings(TypeRef targetType)
    {
        foreach (var c in GetConstructors(targetType))
        {
            if (!c.IsPublic) continue;
            foreach (var p in c.Parameters)
            {
                if (p.SourcePropertyName != null) return true;
            }
        }
        return false;
    }

    /// <summary>
    /// 显式 ctor 绑定实参构造——绑定表命中替代同名比对
    /// （谓词变化）：绑定源属性直访 <c>src.{Name}</c>，按既有类型适配链构造实参
    /// （同型直连 / IsImplicitConvertible 强转 / TypeConvertHelper——与 BuildConstructorArgs
    /// 同口径）；命中同名 pm（pm.Target.Name == 形参名）时 When 守卫三元与 Convert
    /// 静态调用继承（"命中的仍是既有 PropertyMappings 条目"）；绑定源不可达（提取期
    /// F51 已拦截，防御）返回 false 落回既有同名匹配。
    /// <para>param.SourcePropertyName 为 null（未用 MapCtorParam）恒返回 false——调用方产物
    /// 与现状逐字节等价（B9 字节门）。</para>
    /// </summary>
    /// <param name="mapping">映射快照（源属性从 SourceProperties 按名解析）</param>
    /// <param name="param">构造器形参快照（SourcePropertyName 非空 = 绑定命中）</param>
    /// <param name="arg">产出实参表达式（命中时有效）</param>
    /// <returns>true = 绑定实参已构造（调用方跳过同名匹配）</returns>
    internal static bool TryBuildBoundConstructorArg(MappingSnapshot mapping, ConstructorParameterRef param, out string arg)
    {
        arg = "";
        var boundName = param.SourcePropertyName;
        if (string.IsNullOrEmpty(boundName)) return false;

        var boundSrc = mapping.SourceProperties.FirstOrDefault(p =>
            System.StringComparer.OrdinalIgnoreCase.Equals(p.Name, boundName));
        if (boundSrc == null) return false; // 绑定源不可达——落回同名匹配（防御；F51 提取期已拦）

        // 同名 pm（修饰继承载体）；反向写回属性不参与构造器参数匹配（与 同判）
        var boundPm = mapping.PropertyMappings.FirstOrDefault(pm =>
            !pm.IsReverseWriteBack
            && System.StringComparer.OrdinalIgnoreCase.Equals(pm.Target.Name, param.Name));

        var paramType = param.Type.FullName;
        var srcType = boundSrc.Type.FullName;
        // 绑定源属性名 @ 转义（用户属性名可为关键字）
        var access = "src." + SourceGenEscape.Identifier(boundSrc.Name);

        // Convert 修饰继承：同名 pm 的转换器作用于绑定源值（T1 无源形态传 null——与 同口径）
        if (boundPm?.ConverterDeclaringType != null)
        {
            arg = ApplyWhenToConstructorArg(boundPm, BuildStaticConverterCall(boundPm.ConverterDeclaringType,
                boundPm.ConverterMethodName!, boundPm.ConverterShape,
                boundPm.Source == null ? null : access, "src"), param.Type);
            return true;
        }

        // 类型适配链（同型直连/隐式强转/运行时转换）+ When 守卫继承（同名 pm 条件三元）
        var raw = srcType == paramType
            ? access
            : TypeRefHelpers.IsImplicitConvertible(boundSrc.Type, param.Type)
                ? $"({paramType}){access}"
                : $"NCMapper.TypeConvertHelper.ConvertValue<{srcType}, {paramType}>({access})!";
        arg = boundPm != null ? ApplyWhenToConstructorArg(boundPm, raw, param.Type) : raw;
        return true;
    }

    /// <summary>
    /// F37（NCMAP_F37）报告——构造器一体化目标（实参/init-only 初始化器
    /// 即首组赋值，构造与赋值不可分）无 Before 插入点；双侧通道共用（Fluent .BeforeMapping /
    /// 特性 [BeforeMapping]）。ref 为 null（未声明钩子）时短路零输出；原发射形态保留，钩子不发射。
    /// 多站点触发（Core 构造路径/分支①含 init-only/内联构造/fallback）经 AddDistinct 按
    /// (mapping, 诊断值) 去重——同对只报一次。ctx 为 null 时静默（兼容无上下文调用）。
    /// </summary>
    /// <param name="ctx">生成期上下文（null 时静默）</param>
    /// <param name="mapping">映射快照</param>
    internal static void ReportBeforeMappingUninsertableIfNeeded(GenerationContext? ctx, MappingSnapshot mapping)
    {
        if (ctx == null || string.IsNullOrEmpty(mapping.BeforeMappingMethodRef)) return;
        ctx.Diagnostics.AddDistinct(mapping, new DiagnosticSnapshot
        {
            DescriptorId = DiagnosticDescriptorsFluent.BeforeMappingUninsertableTargetRule.Id,
            Args = new[] { mapping.TargetType.FullName },
            Location = mapping.TargetIdentifierLocation,
        });
    }

    /// <summary>
    /// 检查映射信息中是否存在 init-only 目标属性 — P1-SHOULD-8
    /// <para>init-only 属性无法用 <c>dst.Prop = value</c> 赋值，需走 object initializer 或构造器参数路径</para>
    /// <para> 自 Mapping.cs 外移（冻结线零余量—— ② 先例化解）。</para>
