    internal static bool HasInitOnlyTargetProperty(MappingSnapshot mapping)
    {
        foreach (var pm in mapping.PropertyMappings)
        {
            if (pm.Target.IsInitOnly == true)
                return true;
        }
        return false;
    }

    /// <summary>
    /// 构建对象初始化器后缀——`new T(...) { Prop = expr }` 的初始化器部分
    /// <para>成员为空返回空字符串（保持既有生成形态不变，基线测试零回归）；
    /// 成员非空返回 " { Prop = expr, ... }"（对象初始化器语法，支持 init setter）。</para>
    /// <para> 自 Mapping.cs 外移（冻结线零余量—— ② 先例化解）。</para>
    /// </summary>
    /// <param name="members">初始化器成员（"Prop = expr" 形式）</param>
    /// <returns>初始化器后缀字符串；成员为空返回空串</returns>
    private static string BuildInitializerSuffix(IReadOnlyList<string>? members)
    {
        if (members is null || members.Count == 0) return string.Empty;

        return " { " + string.Join(", ", members) + " }";
    }

    /// <summary>
    /// 格式化参数的显式默认值为合法 C# 字面量
    /// <para>CW字符串和字符默认值进行转义，防止代码注入</para>
    /// <para>string/char 两分支内联转义删除，改指 SourceGenEscape.Literal 单点</para>
    /// </summary>
    private static string FormatExplicitDefault(object? value, TypeRef paramType)
    {
        if (value == null) return "null";
        if (paramType.SpecialType == SpecialType.System_String)
        {
            return SourceGenEscape.Literal(value.ToString() ?? "");
        }
        if (paramType.SpecialType == SpecialType.System_Char)
        {
            return SourceGenEscape.Literal((char)value);
        }
        if (paramType.SpecialType == SpecialType.System_Boolean)
            return (bool)value ? "true" : "false";
        // CW数值类型使用 InvariantCulture，防止不同 locale 下生成的字面量格式不一致
        if (paramType.SpecialType == SpecialType.System_Single)
            return ((float)value).ToString(System.Globalization.CultureInfo.InvariantCulture) + "f";
        if (paramType.SpecialType == SpecialType.System_Double)
            return ((double)value).ToString(System.Globalization.CultureInfo.InvariantCulture) + "d";
        if (paramType.SpecialType == SpecialType.System_Decimal)
            return ((decimal)value).ToString(System.Globalization.CultureInfo.InvariantCulture) + "m";
        // 枚举默认值显式转换——Roslyn ExplicitDefaultValue 对枚举
        // 返回底层整数，兜底 Convert.ToString 渲染裸整数 → int 不可隐式转枚举 = CS1503。
        // 输出 (枚举类型)底层值 显式转换形态（与运行时枚举构造语义一致）。
        if (paramType.Kind == TypeKind.Enum)
            return $"({paramType.FullName}){Convert.ToString(value, System.Globalization.CultureInfo.InvariantCulture)}";
        return Convert.ToString(value, System.Globalization.CultureInfo.InvariantCulture) ?? "default";
    }

    /// <summary>
    /// 检查类型是否标注了 [MapFrom(typeof(源类型))]（即是否有对应的源生成器方法）— 值版
    /// <para>基于 TypeRef.MapFromSources（Materialize 时物化的 [MapFrom] 构造参数集合）。
    /// internal 化供 GenerationPreparation 表达式化决策调用（逻辑逐行不动）。</para>
    /// </summary>
    internal static bool IsMapFromRegistered(TypeRef sourceType, TypeRef? nestedTgtType = null)
    {
        if (nestedTgtType == null) return false;
        // 检查目标类型是否标注了 [MapFrom(typeof(源类型))]（支持多源 DTO，任一匹配即可）
        return nestedTgtType.MapFromSources.Any(s => TypeRefHelpers.IsSameType(s, sourceType));
    }

    /// <summary>
    /// 构造映射方法名 — 统一处理方法名后缀，解决不同命名空间同名类型的方法名冲突
    /// </summary>
    /// <param name="mapping">映射快照</param>
    /// <param name="prefix">方法名前缀（如 Map, MapList, BuildProjection）</param>
    /// <param name="suffixMap">方法后缀表（可为 null → 空后缀）</param>
    /// <returns>带后缀的方法名（格式：{prefix}_{SourceClassName}{MethodSuffix}_To_{TargetClassName}{MethodSuffix}）</returns>
    private static string GetMethodName(MappingSnapshot mapping, string prefix, Dictionary<string, string>? suffixMap = null)
    {
        var suffix = suffixMap != null ? GetSuffix(suffixMap, mapping) : "";
        return $"{prefix}_{mapping.SourceClassName}{suffix}_To_{mapping.TargetClassName}{suffix}";
    }

    /// <summary>
