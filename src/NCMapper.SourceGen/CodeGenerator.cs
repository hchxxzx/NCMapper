    private static string GetMethodNameWithSuffix(MappingSnapshot mapping, string prefix, string suffix)
        => $"{prefix}_{mapping.SourceClassName}{suffix}_To_{mapping.TargetClassName}{suffix}";

    /// <summary>
    /// 从类型映射表中查找类型的"类名+后缀"，用于嵌套映射引用的方法名构造 — 值版
    /// <para>internal 化供 GenerationPreparation.BuildDeepCopyGraphs 键收集调用（逻辑逐行不动）。</para>
    /// </summary>
    /// <param name="type">要查找的类型快照</param>
    /// <param name="typeNameMap">类型到"类名+后缀"的映射表</param>
    /// <returns>类型对应的"类名+后缀"；如果不在映射表中则返回类型 SimpleName</returns>
    internal static string GetTypeNameWithSuffix(TypeRef type, Dictionary<TypeRef, string> typeNameMap)
    {
        if (typeNameMap.TryGetValue(type, out var name))
            return name;
        return type.SimpleName;
    }

    /// <summary>
    /// 对级后缀查表——按 SuffixKey 同式（src.FullName + 分隔 +
    /// tgt.FullName）查对级后缀表；miss 回落空后缀（miss 场景 = 元素对非注册对，站点不消费该值
    /// 构建生成方法名）。
    /// <para>缺陷背景：同 src（或同 tgt）多对同名组冲突时，类型级 typeNameMap 的 first-wins 后缀
    /// 与当前元素对的对级后缀可能不一致 → 嵌套/元素调用名与注册名断裂（CS0103）。</para>
    /// <para>定形名 GetPairTypeNameWithSuffix（"命中取后缀后与 SimpleName 拼名"）——实现取
    /// GetPairSuffix 返回对级后缀，双端 SimpleName 拼名由站点完成（单函数双 TypeRef 无法同时返回
    /// 双端名），形态偏差登记。</para>
    /// </summary>
    internal static string GetPairSuffix(TypeRef src, TypeRef tgt, Dictionary<string, string>? suffixMap)
        => suffixMap != null && suffixMap.TryGetValue(src.FullName + "\u0001" + tgt.FullName, out var suffix) ? suffix : "";

    /// <summary>
    /// 检查属性是否在指定方向应被跳过 — 读取 [MapIgnore] 的 Direction 值（值版）
    /// </summary>
    /// <param name="prop">目标属性快照</param>
    /// <param name="toDto">是否为 ToDto 方向</param>
    /// <returns>true 表示应跳过</returns>
    private static bool ShouldSkipForDirection(PropertyRef prop, bool toDto)
    {
        if (!prop.HasMapIgnore) return false;
        return prop.MapIgnoreDirection switch
        {
            0 => true,          // Both
            1 => toDto,         // ToDto
            2 => !toDto,        // ToEntity
            _ => true
        };
    }

    /// <summary>
    /// 标识符净化（生成字段名/方法名用）
    /// </summary>
    private static string SanitizeIdentifier(string input)
    {
        var chars = input.ToCharArray();
        for (int i = 0; i < chars.Length; i++)
        {
            if (i == 0 && !char.IsLetter(chars[i]) && chars[i] != '_')
                chars[i] = '_';
            else if (!char.IsLetterOrDigit(chars[i]) && chars[i] != '_')
                chars[i] = '_';
        }
        return new string(chars);
    }

