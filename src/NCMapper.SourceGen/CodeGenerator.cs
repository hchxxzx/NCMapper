/// <item>CodeGenerator.Mapping.cs — Core/Action/MapList 方法、属性赋值、构造器匹配、内联元素、类型转换与源访问辅助</item>
/// <item>CodeGenerator.Collections.cs — 嵌套类/集合/字典元素级映射发射（元素表达式计划解析与渲染、简单赋值组、内联构造器映射）</item>
/// <item>CodeGenerator.Conversion.cs — 枚举/基本类型转换发射与转换回退（有效源类型判定入口 GetEffectiveSourceType）</item>
