    /// <summary>类型引用文本（去可空注解——typeof/泛型实参不接受 `?` 注解）</summary>
    private static string TypeNameRef(TypeRef type)
        => type.NonNullableFullName.Length > 0 ? type.NonNullableFullName : type.FullName;

    /// <summary>typeof 表达式（SourceType/TargetType 恒 public——NCMAP011 门）</summary>
    private static string TypeOf(TypeRef type)
        => "typeof(" + TypeNameRef(type) + ")";

    /// <summary>
    /// 可空 typeof 表达式（属性类型）：public 可达时 typeof(...)，否则 null
    /// （string 兜底在 TypeName 字段——非 public 属性类型边界登记， 风险行）
    /// </summary>
    private static string NullableTypeOf(TypeRef? type)
        => type != null && type.Accessibility == Accessibility.Public
            ? TypeOf(type)
            : "null";

    private static string Bool(bool value) => value ? "true" : "false";

    // 原私有 Literal(string)（与 CodeGenerator.Literal 同规则）删除，
    // 收敛至 SourceGenEscape.Literal 单点。

    /// <summary>可空字符串字面量（null → "null"）</summary>
    private static string NullableLiteral(string? value)
        => value == null ? "null" : SourceGenEscape.Literal(value);

    /// <summary>字符串数组字面量（空数组 → new string[0]，省一行）</summary>
    private static string StringArray(IEnumerable<string> values)
    {
        var items = values as IList<string> ?? values.ToList();
        if (items.Count == 0) return "new string[0]";
        return "new string[] { " + string.Join(", ", items.Select(SourceGenEscape.Literal)) + " }";
    }

    /// <summary>整数数组字面量（空数组 → new int[0]）—— SourceIndexes 索引段发射用。
    /// B1-04 契约：入参为与 SourcePath 等长的段索引组（无索引段已由调用点以 -1 占位编码）。</summary>
    private static string IntArray(IEnumerable<int> values)
    {
        var items = values as IList<int> ?? values.ToList();
        if (items.Count == 0) return "new int[0]";
        return "new int[] { " + string.Join(", ", items.Select(i => i.ToString(CultureInfo.InvariantCulture))) + " }";
    }
