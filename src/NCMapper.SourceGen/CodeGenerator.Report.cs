using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;

namespace NCMapper.SourceGen;

/// <summary>
/// 映射关系报告生成器 — 将 MappingSnapshot 序列化为 Markdown 格式报告
/// </summary>
internal static partial class CodeGenerator
{
    /// <summary>
    /// 生成映射关系报告（Markdown 格式），通过 AddSource 输出为 .cs 文件
    /// <para>报告内容包裹在 C# 逐字字符串常量中，用户可在 obj/Generated/ 目录查看</para>
    /// </summary>
    /// <param name="spc">源生产上下文</param>
    /// <param name="mappings">映射信息集合</param>
    public static void GenerateReport(
        SourceProductionContext spc,
        ImmutableArray<MappingSnapshot?> mappings)
    {
        if (mappings.IsDefaultOrEmpty) return;

        var sb = new StringBuilder();
        sb.AppendLine("# NCMapper 映射关系报告");
        sb.AppendLine();
        // 移除 DateTime.UtcNow 时间戳，确保增量生成器确定性构建
        // 相同源码 + 相同编译器版本应产生完全相同的输出
        sb.AppendLine($"映射对数量: {mappings.Count(m => m != null)}");
        sb.AppendLine();

        foreach (var mapping in mappings)
        {
            if (mapping == null) continue;

            var sourceName = mapping.SourceType.SimpleName;
            var targetName = mapping.TargetType.SimpleName;

            sb.AppendLine($"## {sourceName} → {targetName}");
            sb.AppendLine("| 源字段 | 目标字段 | 映射方式 | 备注 |");
            sb.AppendLine("|--------|---------|---------|------|");

            foreach (var pm in mapping.PropertyMappings)
            {
                var sourceField = GetSourceFieldName(pm);
                var targetField = pm.Target.Name;
                var (mapType, note) = GetMapTypeAndNote(pm);

                sb.AppendLine($"| {sourceField} | {targetField} | {mapType} | {note} |");
            }

            sb.AppendLine();
        }

        // 将 Markdown 内容转义为 C# 逐字字符串（" → ""）
        var reportContent = sb.ToString().Replace("\"", "\"\"");

        var csContent = new StringBuilder();
        csContent.AppendLine("// <auto-generated/>");
        csContent.AppendLine("// NCMapper 映射关系报告（Markdown 格式）");
        csContent.AppendLine("// 此文件由源生成器在编译时生成，包含所有 [MapFrom] 标注类型的映射关系");
        csContent.AppendLine("// 报告开关：<NCMapperGenerateReport>true</NCMapperGenerateReport>");
        csContent.AppendLine();
        csContent.AppendLine("namespace NCMapper.Generated");
        csContent.AppendLine("{");
        csContent.AppendLine("    /// <summary>");
        csContent.AppendLine("    /// 映射关系报告 — 编译时生成的 Markdown 格式映射关系文档");
        csContent.AppendLine("    /// </summary>");

        csContent.AppendLine("    internal static class MappingReport");
        csContent.AppendLine("    {");
        csContent.AppendLine("        /// <summary>");
        csContent.AppendLine("        /// 映射关系报告内容（Markdown 格式）");
        csContent.AppendLine("        /// </summary>");

        csContent.AppendLine("        internal const string Report = @\"" + reportContent + "\";");
        csContent.AppendLine("    }");
        csContent.AppendLine("}");

        spc.AddSource("NCMapperMappingReport.g.cs", csContent.ToString());
    }

    /// <summary>
    /// 获取源字段名称（支持导航属性路径）
    /// </summary>
    /// <param name="pm">属性映射信息</param>
    /// <returns>源字段名称（如 "Customer.Name"）</returns>
    private static string GetSourceFieldName(PropertyMappingSnapshot pm)
    {
        if (pm.Source == null) return "—";

        // 单段集合索引（"B[0]"，Count==1）也走路径显示；索引段带 [n] 后缀
        if (pm.SourcePath != null && (pm.SourcePath.Count > 1 || pm.HasIndex))
        {
            var sb = new System.Text.StringBuilder();
            for (var i = 0; i < pm.SourcePath.Count; i++)
            {
                if (i > 0) sb.Append('.');
                sb.Append(pm.SourcePath[i].Name);
                if (pm.SourceIndexes.Count > i && pm.SourceIndexes[i] is int n)
                    sb.Append($"[{n}]");
            }
            return sb.ToString();
        }

        return pm.Source.Name;
    }

    /// <summary>
    /// 从 FQN（物化期 ToDisplayString）提取简短类型名（报告备注列显示用）—
    /// 截去泛型实参段后取末段（. / + 分隔；嵌套与命名空间同口径）
    /// </summary>
    private static string GetSimpleTypeName(string fqn)
    {
        var cut = fqn.IndexOf('<');
        var name = cut > 0 ? fqn.Substring(0, cut) : fqn;
        var idx = Math.Max(name.LastIndexOf('.'), name.LastIndexOf('+'));
        return idx >= 0 ? name.Substring(idx + 1) : name;
    }

    /// <summary>
    /// 获取映射方式和备注
    /// </summary>
    /// <param name="pm">属性映射信息</param>
    /// <returns>映射方式字符串和备注字符串的元组</returns>
    private static (string mapType, string note) GetMapTypeAndNote(PropertyMappingSnapshot pm)
    {
        // [Convert] 静态方法转换器（可与 [Mask] 共存）— 三字段（FQN.方法名）
        if (pm.ConverterDeclaringType != null)
        {
            var convNote = $"{GetSimpleTypeName(pm.ConverterDeclaringType)}.{pm.ConverterMethodName}";
            if (pm.MaskType != null)
                return ("[Convert]+[Mask]", $"{convNote} + {pm.MaskType!.SimpleName}");
            return ("[Convert]", convNote);
        }

        // FormatThenMask 双标（先格式化再脱敏）—— 报告标签补 Format 分支（
        // 已判定覆盖：此前双标落 [Mask] 单标、Format 信息丢失）；备注序 = 施加序
        //（格式化先、脱敏后，与 [Convert]+[Mask] 备注序同构）
        if (pm.MaskType != null && pm.FormatString != null)
            return ("[MapFormat]+[Mask]", $"\"{pm.FormatString}\" + {pm.MaskType!.SimpleName}");

        // [Mask] 脱敏——显式异名/多段来源时备注附来源（显式来源组合标签口径：来源信息与
        // 变换信息组合呈现；同名单段既有场景备注不变——产物一致纪律）
        if (pm.MaskType != null)
        {
            var maskNote = pm.MaskType!.SimpleName;
            if (pm.SourcePath is { Count: > 1 } || pm.HasIndex
                || (pm.Source != null && !string.Equals(pm.Source.Name, pm.Target.Name, StringComparison.OrdinalIgnoreCase)))
                maskNote += $" ← {GetSourceFieldName(pm)}";
            return ("[Mask]", maskNote);
        }

        // [MapFormat] 格式化单标—— 补 Format 分支（此前落 direct/rename 分支、格式化标识丢失）
        if (pm.FormatString != null)
            return ("[MapFormat]", $"\"{pm.FormatString}\"");

        // 多段路径（推导扁平化/显式点路径； 改键 + PathOrigin 措辞区分；
        // 单段集合索引同样属显式路径语义）
        if (pm.SourcePath != null && (pm.SourcePath.Count > 1 || pm.HasIndex))
        {
            return pm.PathOrigin == PathOrigin.ExplicitDotPath
                ? ("explicit dot path", "显式点路径")
                : ("navigation flatten", "自动推断导航属性");
        }

        // 异名映射
        if (pm.Source != null && !string.Equals(pm.Source.Name, pm.Target.Name, StringComparison.OrdinalIgnoreCase))
        {
            var srcType = pm.Source.Type.MinimallyQualifiedName;
            var tgtType = pm.Target.Type.MinimallyQualifiedName;
            var note = srcType == tgtType ? "" : $"{srcType} → {tgtType}";
            return ("[MapProperty] rename", note);
        }

        // 同名直接映射
        {
            var srcType = pm.Source?.Type.MinimallyQualifiedName ?? "";
            var tgtType = pm.Target.Type.MinimallyQualifiedName;
            var note = srcType == tgtType ? "" : $"{srcType} → {tgtType}";
            return ("direct", note);
        }
    }
}
