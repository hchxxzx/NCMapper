// ============================================================================
// SnapshotMetadataEmitter — 快照 → 运行时可达元数据发射器
// ----------------------------------------------------------------------------
// 输入：双通道合并后的 MappingSnapshot 集合（DualDriverArbiter.MergeAndArbitrate 产物，
//       复用开源仓既有物化管线—— 只做「快照 → 发射」新段，不动物化）。
// 输出：NCMapper_RuntimeSnapshotMetadata.g.cs —— 用户程序集内的注册代码
//       （[ModuleInitializer] 形态，仿 CodeGenerator.GenerateModuleInitializer 先例：
//        NCMapper.Generated.GeneratedMapperInitializer + RegisterGeneratedCore<S,T> 注册行）。
//
// 发射纪律（spike D1 通过标准， 原样继承）：
//   - 零 internal 符号引用：产物只含 ①public 类型 typeof/类型字面量（用户实体/DTO +
//     global::NCMapper.Runtime.* 承载类型 + global::NCMapper.Attributes.MapFromAttribute）②string/bool/int 字面量——
//     快照 internal 类型（TypeRef/PropertyRef/...）仅在本发射器内被消费转译，绝不出现在产物文本中；
//   - SkipCodeGeneration 条目（NCMAP011 non-public / F11 跨通道冲突 / F16 Fluent 同对重复）不发射——
//     typeof 引用会 CS0122（non-public）且冲突对语义未定；
//   - typeof 可达性：属性类型仅 Accessibility==Public 时发射 typeof 引用
//     （TypeRef.NonNullableFullName 去可空注解——typeof 不接受 `?` 注解），否则 null + TypeName 字符串兜底；
//   - 排序确定性：(SourceFqn, TargetFqn) 序——同输入恒同产物（D5 字节可重复前提）。
//
// 建议 2每条 (S,T) 对发射一个共享 MapFromAttribute 实例（仅 MapFrom 通道），
// 在该对全部 slot 上回填 HasMapFromAttribute=true/MapFromAttribute=实例；Fluent 通道两字段恒 false/null。
// 消费端经 TryGetMappingMeta 门面读 view.MapFromAttribute 时无需再反射（消除"注册表命中但无特性实例"语义缺口）。
// ============================================================================
using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace NCMapper.SourceGen;

/// <summary>
/// 快照运行时可达元数据发射器（L-1 主件——读快照消费子集，生成用户侧注册代码）
/// </summary>
internal static class SnapshotMetadataEmitter
{
    /// <summary>L-1 发射产物 HintName（区别于主生成器 NCMapper_Generated_GeneratedMapper.g.cs）</summary>
    internal const string HintName = "NCMapper_RuntimeSnapshotMetadata.g.cs";

    /// <summary>
    /// Fluent 身份登记产物 HintName
    /// 独立输出节点（不受 NCMapperEmitRuntimeSnapshot 控制），G1-① 显式 off 态兜底数据源
    /// </summary>
    internal const string IdentityHintName = "NCMapper_FluentSnapshotRegistry.g.cs";

    /// <summary>
    /// 发射 Fluent 通道身份级登记代码
    /// </summary>
    /// <param name="mappings">双通道合并快照（含 null/SkipCodeGeneration 条目——内部过滤）</param>
    /// <returns>生成代码文本；无 Fluent 通道条目时返回 null（调用方不 AddSource——零产物）</returns>
    /// <remarks>
    /// 身份级最小登记口径：仅 Source/Target 类型对 + Channel=Fluent + IsFluentForward=true——
    /// 属性明细仍由开关内明细段（<see cref="Emit"/>）承载（职责分离：静态身份登记 = 显式 off 态兜底用）。
    /// 默认 on 态同对双笔登记由 <c>RuntimeSnapshotStore.Register</c> 幂等合并（明细优先，R-B）收敛。
    /// [MapFrom] 通道不在本段发射（显式 off 态走既有反射回退，行为不变）。
    /// </remarks>
    public static string? EmitIdentity(ImmutableArray<MappingSnapshot?> mappings)
    {
        // 排序 + 过滤（与 Emit 同口径：SkipCodeGeneration 三类不发射；仅 Fluent 通道条目）
        var ordered = mappings
            .Where(m => m != null && !m.SkipCodeGeneration)
            .Select(m => m!)
            .Where(m => m.IsFluentForward)
            .OrderBy(m => m.SourceType.FullName, StringComparer.Ordinal)
            .ThenBy(m => m.TargetType.FullName, StringComparer.Ordinal)
            .ToList();
        if (ordered.Count == 0) return null;

        var sb = new StringBuilder(1024);
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Fluent 通道身份级登记（独立输出节点——不受 NCMapperEmitRuntimeSnapshot 控制；");
        sb.AppendLine("// 同读总开关 NCMapperSourceGenEnabled，总开关关闭时与 GeneratedMapper 同消）");
        sb.AppendLine("// 身份级最小登记：Source/Target + Channel + IsFluentForward；属性明细由 NCMapper_RuntimeSnapshotMetadata.g.cs 承载；");
        sb.AppendLine("// 默认 on 态同对双笔登记经 RuntimeSnapshotStore.Register 幂等合并（明细优先）收敛。");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("namespace NCMapper.Runtime");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>Fluent 身份登记——模块加载时执行（与 RuntimeSnapshotMetadataInitializer 共存）</summary>");
        sb.AppendLine("    internal static class FluentSnapshotRegistryInitializer");
        sb.AppendLine("    {");
        sb.AppendLine("        [System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine("        internal static void Initialize()");
        sb.AppendLine("        {");

        for (var i = 0; i < ordered.Count; i++)
        {
            EmitIdentityOne(sb, ordered[i], i);
        }

        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>发射单条 Fluent 身份登记（零明细字段——明细段独有承载）</summary>
    private static void EmitIdentityOne(StringBuilder sb, MappingSnapshot m, int index)
    {
        sb.AppendLine($"            // fluent pair {index}: {m.SourceType.FullName} -> {m.TargetType.FullName}");
        sb.AppendLine("            global::NCMapper.Runtime.RuntimeSnapshotStore.Register(new global::NCMapper.Runtime.RuntimeMapperMetadata");
        sb.AppendLine("            {");
        sb.AppendLine($"                SourceType = {TypeOf(m.SourceType)},");
        sb.AppendLine($"                TargetType = {TypeOf(m.TargetType)},");
        sb.AppendLine($"                SourceTypeFqn = {SourceGenEscape.Literal(m.SourceType.FullName)},");
        sb.AppendLine($"                TargetTypeFqn = {SourceGenEscape.Literal(m.TargetType.FullName)},");
        sb.AppendLine("                Channel = global::NCMapper.Runtime.RuntimeMappingChannel.Fluent,");
        sb.AppendLine("                IsFluentForward = true,");
        sb.AppendLine("            });");
    }

    /// <summary>
    /// 发射运行时元数据注册代码
    /// </summary>
    /// <param name="mappings">双通道合并快照（含 null/SkipCodeGeneration 条目——内部过滤）</param>
    /// <returns>生成代码文本；无有效条目时返回 null（调用方不 AddSource——零产物）</returns>
    public static string? Emit(ImmutableArray<MappingSnapshot?> mappings)
    {
        // 排序 + 过滤（SkipCodeGeneration：NCMAP011 non-public / F11 跨通道冲突 / F16 Fluent 重复）
        var ordered = mappings
            .Where(m => m != null && !m.SkipCodeGeneration)
            .Select(m => m!)
            .OrderBy(m => m.SourceType.FullName, StringComparer.Ordinal)
            .ThenBy(m => m.TargetType.FullName, StringComparer.Ordinal)
            .ToList();
        if (ordered.Count == 0) return null;

        var sb = new StringBuilder(4096);
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// 快照运行时可达元数据（NCMapperEmitRuntimeSnapshot=true 时发射）");
        sb.AppendLine("// 仿 Mapper.GeneratedCache<TSource,TTarget>（Mapper.cs:36-67）+ GeneratedMapperInitializer（CodeGenerator.cs）注册形态");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("namespace NCMapper.Runtime");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>L-1 运行时元数据注册——模块加载时执行（与 NCMapper.Generated.GeneratedMapperInitializer 共存）</summary>");
        sb.AppendLine("    internal static class RuntimeSnapshotMetadataInitializer");
        sb.AppendLine("    {");
        sb.AppendLine("        [System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine("        internal static void Initialize()");
        sb.AppendLine("        {");

        for (var i = 0; i < ordered.Count; i++)
        {
            EmitOne(sb, ordered[i], i);
        }

        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>发射单条 (S,T) 对注册段</summary>
    private static void EmitOne(StringBuilder sb, MappingSnapshot m, int index)
    {
        var varName = "__meta" + index.ToString(CultureInfo.InvariantCulture);
        var mfAttrVar = "__mfAttr" + index.ToString(CultureInfo.InvariantCulture);
        var channel = m.IsFluentForward ? "Fluent" : "MapFrom";
        var hasMapFrom = !m.IsFluentForward; // MapFrom 通道：DTO 标 [MapFrom(typeof(S))]

        // pm 级索引（按目标属性名）——slot 级 Converter/Mask 三元组回填源：
        // PropertyRef 的 ConverterDeclaringType/ConverterMethodName 为上下文相关字段
        //（AllTargetProperties 独立物化不携带——Models.Snapshots.cs SameProperty 注释），
        // 消费承载三元组在 PropertyMappingSnapshot 级（C-2 口径），发射时以 pm 级为准回填 slot。
        var pmByTargetName = new Dictionary<string, PropertyMappingSnapshot>(StringComparer.Ordinal);
        foreach (var pm in m.PropertyMappings)
        {
            pmByTargetName[pm.Target.Name] = pm;
        }

        sb.AppendLine($"            // pair {index}: {m.SourceType.FullName} -> {m.TargetType.FullName} ({channel} channel)");

        // ---- 对级 MapFromAttribute 共享实例（建议 2；仅 MapFrom 通道物化，Fluent 通道不创建）----
        if (hasMapFrom)
        {
            sb.AppendLine($"            var {mfAttrVar} = new global::NCMapper.Attributes.MapFromAttribute({TypeOf(m.SourceType)});");
        }

        // ---- 元数据实例（对象初始化器——全部 public init 属性，零构造歧义）----
        sb.AppendLine($"            var {varName} = new global::NCMapper.Runtime.RuntimeMapperMetadata");
        sb.AppendLine("            {");
        sb.AppendLine($"                SourceType = {TypeOf(m.SourceType)},");
        sb.AppendLine($"                TargetType = {TypeOf(m.TargetType)},");
        sb.AppendLine($"                SourceTypeFqn = {SourceGenEscape.Literal(m.SourceType.FullName)},");
        sb.AppendLine($"                TargetTypeFqn = {SourceGenEscape.Literal(m.TargetType.FullName)},");
        sb.AppendLine($"                Channel = global::NCMapper.Runtime.RuntimeMappingChannel.{channel},");
        sb.AppendLine($"                NoAutoInclude = {Bool(m.NoAutoInclude)},");
        sb.AppendLine($"                IsFluentForward = {Bool(m.IsFluentForward)},");
        sb.AppendLine($"                AfterMappingMethodRef = {NullableLiteral(m.AfterMappingMethodRef)},");
        // ----：前置钩子元数据（条件行——默认值不落产物行，B9 字节门：
        // 无钩子声明映射对产物逐字节不变）----
        if (m.BeforeMappingMethodRef is { } beforeRef)
        {
            sb.AppendLine($"                BeforeMappingMethodRef = {SourceGenEscape.Literal(beforeRef)},");
        }
        // ----：Fluent 树配置/属性级 NoAutoInclude（条件行——默认值不落产物行，F1 字节门）----
        if (m.TreeConfig is { } treeCfg)
        {
            sb.AppendLine($"                TreeConfig = new global::NCMapper.Runtime.RuntimeTreeConfig {{ IdProperty = {SourceGenEscape.Literal(treeCfg.IdProperty)}, ParentIdProperty = {SourceGenEscape.Literal(treeCfg.ParentIdProperty)}, ChildrenProperty = {SourceGenEscape.Literal(treeCfg.ChildrenProperty)} }},");
        }
        if (m.PropertyNoAutoIncludeTargets.Count > 0)
        {
            sb.AppendLine($"                PropertyNoAutoIncludeTargets = new string[] {{ {string.Join(", ", m.PropertyNoAutoIncludeTargets.Select(SourceGenEscape.Literal))} }},");
        }
        if (m.HasComposeMappings)
        {
            sb.AppendLine("                HasComposeMappings = true,");
        }
        // ----：多态分派承载（条件行——默认值不落产物行，字节门：
        // 无 MapSubclass 声明映射对产物逐字节不变；SubclassPairs 非空 = HasSubclassDispatch）----
        if (m.SubclassPairs.Count > 0)
        {
            sb.AppendLine("                HasSubclassDispatch = true,");
        }

        // ---- Properties（正向映射主体）----
        sb.AppendLine("                Properties = new global::NCMapper.Runtime.RuntimePropertyMapping[]");
        sb.AppendLine("                {");
        foreach (var pm in m.PropertyMappings)
        {
            EmitPropertyMapping(sb, pm, pmByTargetName, hasMapFrom, mfAttrVar);
        }
        sb.AppendLine("                },");

        // ---- ComposeMappings（跨表明细——双通道统一发射）----
        // 条件门：无声明整段不落行（F1 字节门精神——纯无 Compose 声明 pair 产物零变化）；
        // 空组照发射（忽略语义承载——物化期"全 Ignore 组不产 cm 不入候选集"，
        // 产物中不存在空 SourcePathNames 行，消费端空组防御分支保留）；14 字段映射与
        // 字段落行条件沿 EmitPropertyMapping 既有约定（null/默认值不落行的三字段除外）
        if (m.ComposeMappings.Count > 0)
        {
            sb.AppendLine("                ComposeMappings = new global::NCMapper.Runtime.RuntimeComposeMapping[]");
            sb.AppendLine("                {");
            foreach (var cm in m.ComposeMappings)
            {
                EmitComposeMapping(sb, cm);
            }
            sb.AppendLine("                },");
        }

        // ---- AllTargetSlots（全部可匹配目标属性信号——Both 忽略差集重建输入）----
        sb.AppendLine("                AllTargetSlots = new global::NCMapper.Runtime.RuntimeTargetPropertySlot[]");
        sb.AppendLine("                {");
        foreach (var prop in m.AllTargetProperties)
        {
            EmitTargetSlot(sb, prop, indent: "                    ", pmByTargetName, hasMapFrom, mfAttrVar);
        }
        sb.AppendLine("                },");

        sb.AppendLine("            };");

        // ---- 注册：泛型键控（候选 a）+ Type 键控注册表（候选 b/c）双写（双写形态）----
        sb.AppendLine($"            global::NCMapper.Runtime.RuntimeSnapshotPair<{TypeNameRef(m.SourceType)}, {TypeNameRef(m.TargetType)}>.Metadata = {varName};");
        sb.AppendLine($"            global::NCMapper.Runtime.RuntimeSnapshotStore.Register({varName});");
    }

    /// <summary>发射单条属性映射对</summary>
    private static void EmitPropertyMapping(StringBuilder sb, PropertyMappingSnapshot pm,
        Dictionary<string, PropertyMappingSnapshot> pmByTargetName, bool hasMapFrom, string mfAttrVar)
    {
        sb.AppendLine("                    new global::NCMapper.Runtime.RuntimePropertyMapping");
        sb.AppendLine("                    {");
        sb.AppendLine("                        Target =");
        EmitTargetSlot(sb, pm.Target, indent: "                            ", pmByTargetName, hasMapFrom, mfAttrVar);
        sb.AppendLine($"                        SourceName = {NullableLiteral(pm.Source?.Name)},");
        sb.AppendLine($"                        SourcePathNames = {StringArray(pm.SourcePath.Select(p => p.Name))},");

        var srcType = pm.Source?.Type;
        sb.AppendLine($"                        SourcePropertyTypeName = {NullableLiteral(srcType?.FullName)},");
        sb.AppendLine($"                        SourcePropertyTypeRef = {NullableTypeOf(srcType)},");

        sb.AppendLine($"                        HasIndex = {Bool(pm.HasIndex)},");
        sb.AppendLine($"                        IsFlattened = {Bool(pm.IsFlattened)},");
        sb.AppendLine($"                        IsReverseWriteBack = {Bool(pm.IsReverseWriteBack)},");

        // pm 级三元组承载（[Convert] / Fluent Convert 注入——消费承载口径）
        sb.AppendLine($"                        HasConverter = {Bool(pm.ConverterDeclaringType != null)},");
        sb.AppendLine($"                        ConverterDeclaringType = {NullableLiteral(pm.ConverterDeclaringType)},");
        sb.AppendLine($"                        ConverterMethodName = {NullableLiteral(pm.ConverterMethodName)},");

        // pm 级脱敏承载（[Mask] / Fluent Mask）
        sb.AppendLine($"                        HasMask = {Bool(pm.MaskType != null)},");
        sb.AppendLine($"                        MaskTypeName = {NullableLiteral(pm.MaskType?.FullName)},");

        sb.AppendLine($"                        IsFromJson = {Bool(pm.IsFromJson)},");

        // pm 级格式化承载（[MapFormat] / Fluent Format）
        // 条件发射（一处，pm 级）：null 不落行 → 无标注映射对产物逐字节不变（字节不变门）；
        // 不得照抄 MaskTypeName 恒发射形态
        if (pm.FormatString != null)
        {
            sb.AppendLine($"                        FormatString = {SourceGenEscape.Literal(pm.FormatString)},");
        }

        // pm 级承载字段（/ additive； 起
        // 双通道补发——pm 双门退役， 审计缺口 /特性对切换快照腿后消费端读快照，
        // 反射回退退居兜底腿不再承担承载面）：条件发射（非默认值不落行）；
        // SourceIgnoreDirection 发射段退役（源侧腿退役——源侧 PropertyRef
        // 不再承载 HasMapIgnore/MapIgnoreDirection， ④ v1.2）
        if (pm.Target.HasMapNoAutoInclude)
        {
            sb.AppendLine("                        IsPropertyNoAutoInclude = true,");
        }
        if (pm.HasIndex)
        {
            // SourceIndexes 与 SourcePath 等长发射
            // 无索引段以 -1 占位（原过滤式 Where(HasValue) 丢段位置：[null, 1, null] 发成 [1]，
            // 运行时消费侧段对齐错位坐实面）；发射门维持（纯无索引 pair 不落行——本 if 块）；
            // RuntimePropertyMapping.SourceIndexes（int[]，Runtime 域）类型禁改——占位符仅本腿契约
            sb.AppendLine($"                        SourceIndexes = {IntArray(pm.SourceIndexes.Select(i => i ?? -1))},");
        }

        // 条件守卫承载（双侧通道——[MapWhen] 特性/Fluent .MapWhen 同字段；
        // 条件发射——null 不落行，无声明映射对产物逐字节不变（字节不变门））。消费锚点：
        // PropertyMatcher 快照读取入口（义务②）→ 运行时回退守卫（A/B 双载体解析）
        // 模式匹配提取非空局部（is { Length: > 0 }）——netstandard2.0 的 string.IsNullOrEmpty
        // 无 [NotNullWhen] 注解，守卫后空态学习不生效（CS8604，--warnaserror 下挡 CI；:193 先例同型）
        if (pm.ConditionMethodRef is { Length: > 0 } whenRef)
        {
            sb.AppendLine($"                        ConditionMethodRef = {SourceGenEscape.Literal(whenRef)},");
            if (pm.ConditionShape != ConditionShape.None)
            {
                sb.AppendLine($"                        ConditionShape = {(int)pm.ConditionShape},");
            }
        }

        sb.AppendLine("                    },");
    }

    /// <summary>
    /// 发射单条 Compose 跨表明细（14 字段全表）
    /// 双通道统一（cm 为双通道合流产物：特性对 [MapProperty(FromSource)] + Fluent FromSource 同载）。
    /// 字段落行条件沿 EmitPropertyMapping 既有约定：HasIndex 恒发射、SourceIndexes 仅 HasIndex 时落行
    ///（等长 -1 占位——B1-04 契约）、FormatString/ConditionMethodRef null 不落行（F2 证伪教训——
    /// 不得照抄 MaskTypeName 恒发射形态）。
    /// </summary>
    private static void EmitComposeMapping(StringBuilder sb, ComposeMappingSnapshot cm)
    {
        sb.AppendLine("                    new global::NCMapper.Runtime.RuntimeComposeMapping");
        sb.AppendLine("                    {");
        sb.AppendLine($"                        TargetPropertyName = {SourceGenEscape.Literal(cm.Target.Name)},");
        sb.AppendLine($"                        SubSourceTypeRef = {NullableTypeOf(cm.SubSource)},");
        sb.AppendLine($"                        SubSourceTypeName = {SourceGenEscape.Literal(cm.SubSource.FullName)},");
        sb.AppendLine($"                        SourcePathNames = {StringArray(cm.SourcePath.Select(p => p.Name))},");
        sb.AppendLine($"                        HasIndex = {Bool(cm.HasIndex)},");
        if (cm.HasIndex)
        {
            // B1-04 契约（与 pm 级 SourceIndexes 同款）：与 SourcePath 等长逐段配对，无索引段 -1 占位
            sb.AppendLine($"                        SourceIndexes = {IntArray(cm.SourceIndexes.Select(i => i ?? -1))},");
        }
        sb.AppendLine($"                        HasConverter = {Bool(cm.ConverterDeclaringType != null)},");
        sb.AppendLine($"                        ConverterDeclaringType = {NullableLiteral(cm.ConverterDeclaringType)},");
        sb.AppendLine($"                        ConverterMethodName = {NullableLiteral(cm.ConverterMethodName)},");
        sb.AppendLine($"                        HasMask = {Bool(cm.MaskType != null)},");
        sb.AppendLine($"                        MaskTypeName = {NullableLiteral(cm.MaskType?.FullName)},");
        sb.AppendLine($"                        IsFromJson = {Bool(cm.IsFromJson)},");
        if (cm.FormatString != null)
        {
            sb.AppendLine($"                        FormatString = {SourceGenEscape.Literal(cm.FormatString)},");
        }
        if (cm.ConditionMethodRef is { Length: > 0 } cmWhenRef)
        {
            // netstandard2.0 string.IsNullOrEmpty 无 [NotNullWhen]（:193 同型——模式匹配收窄）
            sb.AppendLine($"                        ConditionMethodRef = {SourceGenEscape.Literal(cmWhenRef)},");
        }
        sb.AppendLine("                    },");
    }

    /// <summary>方向底层值 → 枚举名字文本（0=Both/1=ToDto/2=ToEntity； G5 发射用——生成器零核心库依赖）</summary>
    private static string DirectionName(int direction) => direction switch
    {
        1 => "ToDto",
        2 => "ToEntity",
        _ => "Both",
    };

    /// <summary>发射目标属性信号槽（PropertyRef 消费子集；Converter 三元组以 pm 级回填为准）</summary>
    private static void EmitTargetSlot(StringBuilder sb, PropertyRef prop, string indent,
        Dictionary<string, PropertyMappingSnapshot> pmByTargetName, bool hasMapFrom, string mfAttrVar)
    {
        // pm 级三元组回填（AllTarget 独立物化不携带上下文相关字段——发射端以消费承载 pm 级为准）
        pmByTargetName.TryGetValue(prop.Name, out var pm);

        sb.AppendLine($"{indent}new global::NCMapper.Runtime.RuntimeTargetPropertySlot");
        sb.AppendLine($"{indent}{{");
        sb.AppendLine($"{indent}    Name = {SourceGenEscape.Literal(prop.Name)},");
        sb.AppendLine($"{indent}    TypeName = {SourceGenEscape.Literal(prop.Type.FullName)},");
        sb.AppendLine($"{indent}    TypeRef = {NullableTypeOf(prop.Type)},");
        // 建议 2 反射缓存字段：对级共享 MapFromAttribute 实例（MapFrom 通道 true+实例；Fluent 通道 false+null）
        sb.AppendLine($"{indent}    HasMapFromAttribute = {Bool(hasMapFrom)},");
        sb.AppendLine($"{indent}    MapFromAttribute = {(hasMapFrom ? mfAttrVar : "null")},");
        sb.AppendLine($"{indent}    HasMapIgnore = {Bool(prop.HasMapIgnore)},");
        sb.AppendLine($"{indent}    MapIgnoreDirection = {prop.MapIgnoreDirection.ToString(CultureInfo.InvariantCulture)},");
        sb.AppendLine($"{indent}    HasOverrideIgnore = {Bool(prop.HasOverrideIgnore)},");
        sb.AppendLine($"{indent}    HasMapProperty = {Bool(prop.HasMapProperty)},");
        sb.AppendLine($"{indent}    FromField = {NullableLiteral(prop.MapPropertyFromField)},");
        sb.AppendLine($"{indent}    FromSourceTypeName = {NullableLiteral(prop.MapPropertyFromSource?.FullName)},");
        sb.AppendLine($"{indent}    HasMask = {Bool(prop.HasMask || (pm?.MaskType != null))},");
        sb.AppendLine($"{indent}    MaskTypeName = {NullableLiteral(pm?.MaskType?.FullName ?? prop.MaskType?.FullName)},");
        sb.AppendLine($"{indent}    HasConverter = {Bool(prop.HasConvertUsing || pm?.ConverterDeclaringType != null)},");
        sb.AppendLine($"{indent}    ConverterDeclaringType = {NullableLiteral(pm?.ConverterDeclaringType ?? prop.ConverterDeclaringType)},");
        sb.AppendLine($"{indent}    ConverterMethodName = {NullableLiteral(pm?.ConverterMethodName ?? prop.ConverterMethodName)},");
        sb.AppendLine($"{indent}    HasConvertBack = {Bool(prop.HasConvertBackUsing)},");
        sb.AppendLine($"{indent}    ConverterBackDeclaringType = {NullableLiteral(prop.ConverterBackDeclaringType)},");
        sb.AppendLine($"{indent}    ConverterBackMethodName = {NullableLiteral(prop.ConverterBackMethodName)},");
        sb.AppendLine($"{indent}    IsFromJson = {Bool(prop.IsFromJson)},");
        sb.AppendLine($"{indent}}},");
    }

