internal static partial class CodeGenerator
{
    #region 入口编排

    /// <summary>
    /// 生成映射代码（S3，：输出期零 Compilation 依赖——Combine 已解除，
    /// 位置重建 external location + DeepCopy 值域分类零反查）
    /// </summary>
    /// <param name="spc">源生产上下文，用于添加生成的源文件</param>
    /// <param name="mappings">映射快照集合（纯值，缓存零符号）</param>
    /// <param name="prep">发射前准备产物（GenerationPreparation.Prepare 一次构造，发射期零决策）</param>
    /// <param name="globalConfig">全局映射配置快照（合并后；可为 null）——配置非空时模块初始化器输出
    /// <c>Mapper.RegisterGeneratedConfig</c> 快照（D1 PoC 的可观测载体；匹配注入见）</param>
    /// <param name="generationContext">生成期上下文（per-run 诊断收集）</param>
    internal static void GenerateMapperCode(SourceProductionContext spc, System.Collections.Immutable.ImmutableArray<MappingSnapshot?> mappings, GenerationPreparation prep, GlobalConfigSnapshot? globalConfig = null, GenerationContext? generationContext = null)
    {
        // per-run 生成期诊断收集（缓存快照只读）；调用方未提供时自建
        generationContext ??= new GenerationContext(spc.CancellationToken);
        var diagnostics = generationContext.Diagnostics;

        // 发射前准备段在
        // RegisterSourceOutput 回调内一次构造（GenerationPreparation.Prepare）——发射期零决策、零回调；
        // / 
        // 各构造逻辑经 prep 产物消费（宿主：上提三方法 + NestedCycleDetector + ReversePlanner + 分类器）
        var suffixMap = prep.MethodSuffixMap;
        var typeNameMap = prep.TypeNameMap;
        var mutualPairs = prep.MutualPairs;
        var reverseSnapshotTable = prep.ReverseSnapshotTable;

        // 互指映射对 NCMAP025 诊断保留在此（时序不变）
        // 互指对 = (A.SourceType==B.TargetType && A.TargetType==B.SourceType)，生成侧该对不生成
        EmitMutualPairDiagnostics(spc, mappings, mutualPairs);

        // 可生成对键集（MapSubclass 分派链引用防线）——落空（F48 已报）
        // /抑制（F11/F16 Suppress）/互指对不生成方法体，分派链引用将断裂（CS0103）——
        // 构链时查表 miss 即丢弃该分派条目。键口径 = SuffixKey 同式（FullName 二元组）。
        var generatableKeys = new HashSet<string>();
        foreach (var m in mappings)
        {
            if (m == null || m.SkipCodeGeneration) continue;
            if (IsMutualPair(m, mutualPairs)) continue;
            generatableKeys.Add(m.SourceType.FullName + "\u0001" + m.TargetType.FullName);
        }

        // 主 StringBuilder 容量预估—— 基线单对最小夹具
        // 产物 29,355 B（UTF-8，char 数 ≤ 字节数），上取 2 的幂 32,768 chars 单次分配零倍增拷贝
        //（先例 SnapshotMetadataEmitter.cs:71/129 预分配 1024/4096）
        var sb = new StringBuilder(32768);
        sb.AppendLine("//------------------------------------------------------------------------------");
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("//     此代码由 NCMapper 源生成器自动生成。");
        sb.AppendLine("//     版本: 1.0.0-preview.1");
        sb.AppendLine("//     对代码的修改可能在下次编译时丢失。");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("//------------------------------------------------------------------------------");
        sb.AppendLine("#nullable disable");
        sb.AppendLine("#pragma warning disable CS8632 // 可空引用类型注解仅在 #nullable 上下文中使用（生成代码上下文关闭；若未来恢复 #nullable enable，必须同步移除本行）");
        sb.AppendLine("#pragma warning disable CS8669 // 自动生成代码中的可空注解需显式 #nullable 上下文（SDK 10.0.400 实测：生成文件注解噪声报 CS8669 而非 CS8632；若未来恢复 #nullable enable，必须同步移除本行）");
        sb.AppendLine("#pragma warning disable NCMapper001 // 生成代码引用 Pipeline 公共门面（Experimental API）");
        sb.AppendLine();
        sb.AppendLine("namespace NCMapper.Generated");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// NCMapper 源生成器自动生成的映射器 — 标注 [MapFrom] 的 DTO 自动获得编译时映射方法");
        sb.AppendLine("    /// </summary>");

        sb.AppendLine("    internal static class GeneratedMapper");
        sb.AppendLine("    {");

        // W3_1 （C4 前移）：deepCopyTypes 键收集 + deepCopyShapes 分类已在准备段构造（prep.DeepCopyGraphs）

        foreach (var mapping in mappings)
        {
            // 长时间编译时响应取消请求，避免阻塞 IDE
            spc.CancellationToken.ThrowIfCancellationRequested();
            if (mapping == null) continue;
            // NCMAP011：non-public 类型跳过代码生成，仅由 EmitDiagnostics 报告诊断
            // 运行时引擎仍可处理此类型对（通过 Mapper.Map 走运行时表达式树路径）
            if (mapping.SkipCodeGeneration) continue;

            // 互指对整体跳过生成（正向方法族 + 反向翻转 + Compose + DeepCopy 收集
            // 均不生成；运行时按名匹配兜底）；诊断已在 EmitMutualPairDiagnostics 输出
            if (IsMutualPair(mapping, mutualPairs)) continue;

            var methodSuffix = GetSuffix(suffixMap, mapping);

            // MapSubclass 四族分派链构造（SubclassPairs
            // 空 → null，四族发射零分派产物行，G3 字节门；反向族不构造——O-2 反向不消费分派）；
            // generatableKeys 查表（落空/抑制对不进链，防 CS0103 引用断裂）
            var subclassDispatch = BuildSubclassDispatchChain(mapping, suffixMap, generatableKeys);

            // L-08→M: 按 mapping 粒度 try/catch，单个异常类型不导致所有映射代码丢失
            try
            {
                GenerateCoreMapMethod(sb, mapping, typeNameMap, generationContext, methodSuffix, subclassDispatch);
                GenerateActionMapMethod(sb, mapping, methodSuffix);
                GenerateUpdateMapMethod(sb, mapping, typeNameMap, generationContext, methodSuffix, subclassDispatch);
                GenerateMapListMethod(sb, mapping, typeNameMap, generationContext, methodSuffix, subclassDispatch);
                // 批量就地映射方法（正向；反向区 不生成，设计）
                GenerateMapListIntoMethod(sb, mapping, typeNameMap, generationContext, methodSuffix, subclassDispatch);

                // 有跨表字段 → 生成 Compose 部分更新方法和合成方法
                if (mapping.ComposeMappings.Count > 0)
                {
                    GenerateComposeUpdateMethods(sb, mapping, methodSuffix);
                    GenerateComposeMethod(sb, mapping, methodSuffix);
                }

                // deepCopyTypes 键收集已入 prep.DeepCopyGraphs（TypeName 统一分配）

                // 反向快照消费唯一构造点表（过滤后；反向诊断已在构造点发射一次）
                var reverseMapping = reverseSnapshotTable[mapping];
                if (reverseMapping != null)
                {
                    GenerateCoreMapMethod(sb, reverseMapping, typeNameMap, generationContext, methodSuffix);
                    GenerateActionMapMethod(sb, reverseMapping, methodSuffix);
                    GenerateUpdateMapMethod(sb, reverseMapping, typeNameMap, generationContext, methodSuffix);
                    GenerateMapListMethod(sb, reverseMapping, typeNameMap, generationContext, methodSuffix);
                }

                // 静态 advisory（定性
                // 编译期静态可判定谓词，SubclassPairs 非空每对一次 Info）：②反向不对称（正向分派 +
                // 反向自动生成但不分派——dst 固定型，反向子类专有字段不填充）+
                // ③双实例匹配残留面（Update/MapListInto dst 运行时非子类目标类型时回落基类体）。
                if (subclassDispatch != null)
                {
                    var advisory = reverseMapping != null
                        ? "reverse-asymmetry, dual-instance-fallback"
                        : "dual-instance-fallback";
                    spc.ReportDiagnostic(Diagnostic.Create(
                        DiagnosticDescriptorsFluent.SubclassDispatchAdvisoryRule,
                        RebuildTargetLocation(mapping) ?? Location.None,
                        mapping.SourceType.FullName, mapping.TargetType.FullName, advisory));
                }
            }
            catch (Exception ex) when (ex is not OperationCanceledException)
            {
                // L-08→M: 报告 NCMAP099 警告（生成失败），继续处理其他映射
                spc.ReportDiagnostic(Diagnostic.Create(
                    DiagnosticDescriptors.GenerationFailedRule,
                    RebuildTargetLocation(mapping) ?? Location.None,
                    mapping.SourceType.FullName, mapping.TargetType.FullName, ex.Message));
            }
        }

        // W3_1 （C4 前移）：nodeMap 合并 + Classify 循环（含防御分支）已在准备段构造
        // （S3， 值域分类零反查）；发射端仅遍历 prep.DeepCopyGraphs
        // （Dictionary 插入序与原构造序一致——发射序逐字节等价）
        foreach (var kvp in prep.DeepCopyGraphs)
        {
            spc.CancellationToken.ThrowIfCancellationRequested();
            var graph = kvp.Value;
            // 防御条目（Node=null，节点缺失——不应发生）：跳过方法生成（原 continue 等价），
            // 注册行仍输出（GenerateModuleInitializer 按 Shape=Unknown → acyclic:false）
            if (graph.Node == null) continue;
            GenerateDeepCopyForType(sb, kvp.Key, graph.TypeName, spc, graph.Node, graph.Shape, graph.UnknownEdges);
        }

        // 生成 ValidateGenerated 方法 — 编译时验证结果，零反射，AOT 友好
        // （读 transform 初始 + per-run 追加的合并诊断列表，与现状可见集一致）
        GenerateValidateMethod(sb, mappings, mutualPairs, generationContext);

        // 生成 [Mask] 脱敏器静态单例字段
        GenerateMaskFields(sb, mappings, mutualPairs, suffixMap);

        // B 形态 MapWhen 谓词方法本体发射（内联转录产物落地
        // Fluent .MapWhen 内联 lambda → GeneratedMapper 私有静态方法；A 形态用户方法不发射仅引用）
        GenerateWhenPredicateMethods(sb, mappings, mutualPairs);

        // B 形态转换器方法本体发射（F26 收窄——Fluent .Convert/.ConvertBack
        // 内联 lambda 转录产物落地；无 B 形态声明零输出——字节不变门）
        GenerateConverterMethods(sb, mappings, mutualPairs, reverseSnapshotTable);

        sb.AppendLine("    }");
        sb.AppendLine();

        // 生成扩展方法类（零委托直调，JIT 可内联）
        // 扩展生成为第三消费方——同表快照（过滤后，同一实例）
        GenerateExtensionClass(sb, mappings, mutualPairs, suffixMap, reverseSnapshotTable, generationContext);

        // 生成模块初始化器（注册所有生成的方法到 Mapper）
        // deepCopyTypes/deepCopyShapes 两表合一为 prep.DeepCopyGraphs（TypeName/Shape 随图携带）
        GenerateModuleInitializer(sb, mappings, prep.DeepCopyGraphs, globalConfig, mutualPairs, suffixMap, reverseSnapshotTable);

        sb.AppendLine("}");
        spc.AddSource("NCMapper_Generated_GeneratedMapper.g.cs", sb.ToString());
    }

    /// <summary>
    /// 重建目标类型标识符位置（external location，不依赖 Compilation）
    /// <para>即 TargetIdentifierLocation 重建为输出期 Location（NCMAP099 异常定位用）</para>
    /// <para>internal 化供 ReversePlanner 调用（反向 NCMAP099 定位）</para>
    /// </summary>
    internal static Location? RebuildTargetLocation(MappingSnapshot mapping)
    {
        if (mapping.TargetIdentifierLocation == null) return null;
        var loc = mapping.TargetIdentifierLocation.Value;
        return Location.Create(loc.FilePath, loc.Span, loc.LineSpan);
    }

    /// <summary>
    /// 检测互指映射对— (A.SourceType==B.TargetType &amp;&amp; A.TargetType==B.SourceType)
    /// <para>返回 source→target 有向对字典；仅 SkipCodeGeneration=false 的 mapping 参与判定
    /// （non-public 类型不生成代码，无互指冲突语义）。</para>
    /// </summary>
    /// <param name="mappings">映射快照集合</param>
    /// <returns>互指有向对字典（TypeRef 值相等）</returns>
    internal static Dictionary<TypeRef, TypeRef> DetectMutualPairs(System.Collections.Immutable.ImmutableArray<MappingSnapshot?> mappings)
    {
        // 内层 O(N) 全扫描 → 源类型索引 + 候选列表（O(N·k)，
        // k = 同源类型映射目标数、常规 ≈1）。索引键 = TypeRef 字典（值相等语义 = EqualityKey
        // Ordinal，与 IsSameType 同语义——Models.Snapshots.cs:197/:202 同证）；互指双判定条件
        // 逐字保留（第二条件对索引命中冗余，保真防语义漂移）；自指排除 = 下标判等（与原
        // ReferenceEquals(a, b) 同语义）；赋值序 = 外层声明序（与原版一致，同键重复赋同值无序差）。
        var bySource = new Dictionary<TypeRef, List<int>>();
        for (int i = 0; i < mappings.Length; i++)
        {
            var m = mappings[i];
            if (m == null || m.SkipCodeGeneration) continue;
            if (!bySource.TryGetValue(m.SourceType, out var list))
                bySource[m.SourceType] = list = new List<int>();
            list.Add(i);
        }

        var mutual = new Dictionary<TypeRef, TypeRef>();
        for (int i = 0; i < mappings.Length; i++)
        {
            var a = mappings[i];
            if (a == null || a.SkipCodeGeneration) continue;
            if (!bySource.TryGetValue(a.TargetType, out var candidates)) continue;
            foreach (var j in candidates)
            {
                if (j == i) continue;
                var b = mappings[j]!;
                // 交叉判定收敛至共享规则（-1，NCMapper.Shared.MutualMapPairRules）
                if (Shared.MutualMapPairRules.IsMutualMappingPair(
                        TypeRefHelpers.IsSameType(a.SourceType, b.TargetType),
                        TypeRefHelpers.IsSameType(a.TargetType, b.SourceType)))
                {
                    mutual[a.SourceType] = a.TargetType;
                }
            }
        }
        return mutual;
    }

    /// <summary>
    /// 判断映射是否属于互指对（生成侧应跳过）
    /// <para>internal 化供 ReversePlanner 调用（反向表构造同过滤）</para>
    /// </summary>
    /// <param name="mapping">映射快照</param>
    /// <param name="mutualPairs">互指有向对字典</param>
    /// <returns>属于互指对返回 true</returns>
    internal static bool IsMutualPair(MappingSnapshot mapping, Dictionary<TypeRef, TypeRef> mutualPairs)
    {
        return mutualPairs.TryGetValue(mapping.SourceType, out var tgt)
            && TypeRefHelpers.IsSameType(tgt, mapping.TargetType);
    }

    /// <summary>
    /// 输出互指对诊断（NCMAP025，Error 级）— 每对两处声明位置各报一条
    /// <para>互指对在字典中存有双向键（X→Y 与 Y→X 各一条），此处仅对"显示名较小为源"的方向
    /// 处理一次并报出双向两条，避免重复；确定性：按源类型显示名排序输出，跨构建稳定。</para>
    /// </summary>
    /// <param name="spc">源生产上下文</param>
    /// <param name="mappings">映射快照集合</param>
    /// <param name="mutualPairs">互指有向对字典</param>
    private static void EmitMutualPairDiagnostics(SourceProductionContext spc, System.Collections.Immutable.ImmutableArray<MappingSnapshot?> mappings, Dictionary<TypeRef, TypeRef> mutualPairs)
    {
        if (mutualPairs.Count == 0) return;
        // ReportMutualDiagnostic 每 (source,target) 线性
        // FirstOrDefault（O(对数×N)）→ 预建 (S,T)→首个 mapping 查表（一次遍历 O(N)；
        // TryAdd 保首中 = FirstOrDefault 声明序首中同语义，键 TypeRef 值相等 = IsSameType 同语义）；
        // miss 回退线性扫描（防御不变量——预建覆盖面为 mutualPairs 键值来源集超集，常规不可达）。
        var byPair = new Dictionary<(TypeRef, TypeRef), MappingSnapshot?>();
        foreach (var m in mappings)
        {
            if (m == null) continue;
            // netstandard2.0 无 Dictionary.TryAdd 扩展（B1-10 BuildSimpleAssignmentsTable 同款 ContainsKey 形态）
            if (!byPair.ContainsKey((m.SourceType, m.TargetType)))
                byPair[(m.SourceType, m.TargetType)] = m;
        }
        foreach (var pair in mutualPairs
            .Where(kv => string.CompareOrdinal(kv.Key.FullName, kv.Value.FullName) <= 0)
            .OrderBy(kv => kv.Key.FullName, System.StringComparer.Ordinal))
        {
            ReportMutualDiagnostic(spc, mappings, byPair, pair.Key, pair.Value);
            ReportMutualDiagnostic(spc, mappings, byPair, pair.Value, pair.Key);
        }
    }

    /// <summary>
    /// 报告单条互指诊断（定位分通道—— T2）
    /// </summary>
    /// <param name="spc">源生产上下文</param>
    /// <param name="mappings">映射快照集合（防御回退线性扫描用）</param>
    /// <param name="byPair">(S,T)→首个 mapping 预建表（B1-11，EmitMutualPairDiagnostics 一次遍历构建）</param>
    /// <param name="source">互指源类型</param>
    /// <param name="target">互指目标类型</param>
    private static void ReportMutualDiagnostic(SourceProductionContext spc, System.Collections.Immutable.ImmutableArray<MappingSnapshot?> mappings, Dictionary<(TypeRef, TypeRef), MappingSnapshot?> byPair, TypeRef source, TypeRef target)
    {
        if (!byPair.TryGetValue((source, target), out var mapping))
        {
            // 防御回退：原线性首中语义（预建表常规必命中，此分支不可达）
            mapping = mappings.FirstOrDefault(m => m != null
                && TypeRefHelpers.IsSameType(m.SourceType, source)
                && TypeRefHelpers.IsSameType(m.TargetType, target));
        }
        var m = mapping!;
        // T2 定位分通道：Fluent 声明的对定位指向 For<S,T>() invocation
        //（ForInvocationLocation 纯值重建）；特性通道维持目标类型声明标识符
        //（TargetIdentifierLocation 既有语义）。纯值重建不依赖 Compilation（S3 同款）。
        var location = m.ForInvocationLocation != null
            ? Location.Create(m.ForInvocationLocation.Value.FilePath, m.ForInvocationLocation.Value.Span, m.ForInvocationLocation.Value.LineSpan)
            : (RebuildTargetLocation(m) ?? Location.None);
        spc.ReportDiagnostic(Diagnostic.Create(
            DiagnosticDescriptors.MutualReferenceRule, location,
            source.FullName, target.FullName));
    }

    /// <summary>
    /// 掩码字段名单点— 声明处与引用处必须一致，
    /// 漂移会导致生成代码引用不存在字段（编译失败）
    /// </summary>
    private static string BuildMaskFieldName(string className, string methodSuffix, string propName)
        => $"__mask_{SanitizeIdentifier(className)}{methodSuffix}_{SanitizeIdentifier(propName)}";

    private static void GenerateMaskFields(StringBuilder sb, System.Collections.Immutable.ImmutableArray<MappingSnapshot?> mappings, Dictionary<TypeRef, TypeRef>? mutualPairs, Dictionary<string, string> suffixMap)
    {
        // 收集唯一掩码字段：fieldName → typeName
        // 收集谓词对齐引用侧全部分流——缺陷态：只查 MaskType
        // 不查方向/SkipCodeGeneration/可访问性/发射形态 → 引用侧跳过的属性字段仍声明 → 声明零
        // 引用（CS0414 面）。B9 等价论证：引用侧跳过 ⇒ 收集侧跳过；引用到达 ⇒ 收集已收集
        //（对照表按两符号各自消费面分列，双向逐谓词对照入）。
        var maskFields = new Dictionary<string, string>();
        foreach (var mapping in mappings)
        {
            if (mapping == null) continue;
            if (mutualPairs != null && IsMutualPair(mapping, mutualPairs)) continue;
            var methodSuffix = GetSuffix(suffixMap, mapping);
            // ① 主循环门对齐：SkipCodeGeneration 映射不生成赋值体（主循环 门）→ 掩码字段零引用
            if (mapping.SkipCodeGeneration) continue;
            var toDto = IsToDtoMapping(mapping);
            foreach (var pm in mapping.PropertyMappings)
            {
                if (pm.MaskType == null) continue;
                // ② 方向门对齐（pm 版 ShouldSkipForDirectionPair——引用侧 :579/:731/:993/:174/:334 同谓词）
                if (ShouldSkipForDirectionPair(pm, toDto)) continue;
                // ③ 可访问性对齐（IsAccessiblePair——引用侧不可访问属性不发射赋值）
                if (!IsAccessiblePair(pm).Ok) continue;
                // ④ 发射形态对齐：掩码引用仅三形态——[Convert] 共存（先转换后脱敏包装）/
                // FormatThenMask 双标（Mask 输入 = 格式化 string 结果，无需源 string）
                // 与标准路径有效源 string（生成侧守卫）；简单路径 Direct/Convert+隐式
                // 含 Mask ⇔ 有效源 string（string→string 恒可赋值，其余类型到 string 无隐式转换）
                var effSrc = GetEffectiveSourceType(pm) ?? pm.Source?.Type;
                if (pm.ConverterDeclaringType == null && pm.FormatString == null
                    && effSrc?.SpecialType != SpecialType.System_String)
                    continue;
                var className = pm.Target.ContainingType?.SimpleName ?? "Anon";
                var fieldName = BuildMaskFieldName(className, methodSuffix, pm.Target.Name);
                if (!maskFields.ContainsKey(fieldName))
                    maskFields[fieldName] = pm.MaskType.FullName;
            }
            // Compose 副源字段 [Mask] 掩码字段收集（与主源字段同口径
            // 与主源同 (DTO类,suffix,Prop) 字典去重共享（first-wins，R4 先存口径）；无孤儿字段——
            // 发射侧消费点 GenerateComposeUpdateMethods 用同一 BuildMaskFieldName 公式引用）
            // 副源段同口径对齐（引用侧 = GenerateComposeUpdateMethods 四段序分支①/②）
            foreach (var cm in mapping.ComposeMappings)
            {
                if (cm.MaskType == null) continue;
                // ② 方向门对齐（值版——cm 无 Pair 版包装）
                if (ShouldSkipForDirection(cm.Target, toDto)) continue;
                // ③ 可访问性对齐由提取端承载（ProcessTargetProperty GetMethod null 早退
                // → ComposeMappings 输入集可访问性已保证，收集侧不重复）
                // ④ 发射形态对齐（composeSrcType 口径 = 末段索引时取元素类型）：掩码引用仅三形态——
                // [Convert] 共存（先转换后脱敏包装）/ FormatThenMask 双标（Mask 输入 = 格式化
                // string 结果，无需源 string）/ 与标准路径有效源 string；与主源侧 :380 谓词同口径
                //（漏查 FormatString 会让 Compose 侧 Format+Mask 双标跳过收集，发射侧却引用
                // __mask_* 字段 → CS0103）
                var cmEffSrc = cm.SourceIndexes.Count > 0 && cm.SourceIndexes[cm.SourceIndexes.Count - 1] is int
                    ? (cm.Source.Type.EnumerableElementType ?? cm.Source.Type)
                    : cm.Source.Type;
                if (cm.ConverterDeclaringType == null && cm.FormatString == null
                    && cmEffSrc.SpecialType != SpecialType.System_String)
                    continue;
                var className = cm.Target.ContainingType?.SimpleName ?? "Anon";
                var fieldName = BuildMaskFieldName(className, methodSuffix, cm.Target.Name);
                if (!maskFields.ContainsKey(fieldName))
                    maskFields[fieldName] = cm.MaskType.FullName;
            }
        }
        if (maskFields.Count == 0) return;

        sb.AppendLine();
        sb.AppendLine("        // [Mask] 脱敏器静态单例 — 通过 MaskProvider 解析，支持运行时替换实现");
        foreach (var kvp in maskFields)
            sb.AppendLine($"        private static readonly global::NCMapper.IMask {kvp.Key} = global::NCMapper.MaskProvider.Resolve<{kvp.Value}>();");
    }

    /// <summary>
    /// 方法名冲突检测与后缀分配（纯函数，M-07 根治）— 检测不同命名空间同名类型的方法名冲突，
    /// 为冲突的映射对分配 _2, _3... 后缀；返回值不写入任何缓存对象。
    /// <para>internal 化供 GenerationPreparation.Prepare 上提调用（逻辑逐行不动）。</para>
    /// </summary>
    /// <param name="mappings">映射快照集合</param>
    /// <returns>映射标识（SourceFullName|TargetFullName）→ 后缀字符串 的查表</returns>
    internal static Dictionary<string, string> AssignMethodSuffixes(System.Collections.Immutable.ImmutableArray<MappingSnapshot?> mappings)
    {
        // 收集所有映射对的基础方法名（SourceClassName_To_TargetClassName），检测不同命名空间同名类型冲突
        // 按类型名排序确保后缀分配跨构建确定性
        // 排序产物提取为 ordered，分组收集与后缀分配两循环
        // 统一消费——缺陷态：收集按排序序、分配按原始声明序（foreach mappings）→ 同组内后缀
        // 归属随声明序漂移，跨构建不确定（两序列化产物后缀互换）。
        var ordered = mappings
            .Where(m => m != null)
            .OrderBy(m => m!.SourceType.FullName)
            .ThenBy(m => m!.TargetType.FullName)
            .ToList();
        var methodNameGroups = new Dictionary<string, List<MappingSnapshot>>();
        foreach (var mapping in ordered)
        {
            if (mapping == null) continue;
            var baseName = $"{mapping.SourceClassName}_To_{mapping.TargetClassName}";
            if (!methodNameGroups.TryGetValue(baseName, out var list))
            {
                list = new List<MappingSnapshot>();
                methodNameGroups[baseName] = list;
            }
            list.Add(mapping);
        }

        // 为冲突的映射对分配后缀（第一个无后缀保持兼容，后续 _2, _3...）
        // 分配循环同样按排序序（ordered）遍历——同组内计数次序跨构建确定
        var suffixMap = new Dictionary<string, string>();
        var suffixCounters = new Dictionary<string, int>();
        foreach (var mapping in ordered)
        {
            if (mapping == null) continue;
            var baseName = $"{mapping.SourceClassName}_To_{mapping.TargetClassName}";
            var suffix = "";
            if (methodNameGroups.TryGetValue(baseName, out var group) && group.Count > 1)
            {
                if (!suffixCounters.TryGetValue(baseName, out int counter))
                    counter = 0;
                counter++;
                suffixCounters[baseName] = counter;
                if (counter > 1)
                    suffix = $"_{counter}";
            }
            suffixMap[SuffixKey(mapping)] = suffix;
        }
        return suffixMap;
    }

    /// <summary>
    /// 映射标识键（SourceTypeFullName|TargetTypeFullName）
    /// </summary>
    private static string SuffixKey(MappingSnapshot m)
        => m.SourceType.FullName + "\u0001" + m.TargetType.FullName;

    /// <summary>查表取映射后缀（不存在返回空串；反向映射回退正向键——
    /// 反向方法复用正向后缀，符号版语义：reverse.MethodSuffix = forward.MethodSuffix）</summary>
    internal static string GetSuffix(Dictionary<string, string> suffixMap, MappingSnapshot mapping)
    {
        if (suffixMap.TryGetValue(SuffixKey(mapping), out var suffix)) return suffix;
        // 反向回退：reverse 键 (Tgt|Src) 不在表中（正向才入表），用 (Src|Tgt) 查 forward 的后缀
        if (suffixMap.TryGetValue(mapping.TargetType.FullName + "\u0001" + mapping.SourceType.FullName, out var revSuffix))
            return revSuffix;
        return "";
    }

    /// <summary>
    /// MapSubclass 分派链条目（值对象——isinst 匹配类型全名 +
    /// 子类对 Core/Update 方法名）。链顺序 = SubclassPairs 物化期最派生优先排序序
    /// （仲裁——发射端逐序生成 isinst 顺序链，零排序逻辑）。
    /// </summary>
    internal sealed record SubclassDispatchEntry(
        string MatchTypeFullName,
        string TargetTypeFullName,
        string CoreMethodName,
        string UpdateMethodName);

    /// <summary>
    /// 构造基类对分派链（前置 1——子类方法名经
    /// suffixMap 查表消歧：显式声明的子类对可能带同对多版本后缀；合成对恒唯一空后缀）。
    /// SubclassPairs 空 → null（四族发射零分派产物行——G3 字节门）。
    /// 方法名口径 = GetMethodNameWithSuffix 同式（{prefix}_{Src}{suffix}_To_{Tgt}{suffix}）。
    /// generatableKeys 查表——落空/抑制（F11/F16）/互指对不生成方法，
    /// 引用将断裂（CS0103）的分派条目丢弃。
    /// </summary>
    private static List<SubclassDispatchEntry>? BuildSubclassDispatchChain(
        MappingSnapshot mapping, Dictionary<string, string> suffixMap, HashSet<string> generatableKeys)
    {
        if (mapping.SubclassPairs.Count == 0) return null;
        var chain = new List<SubclassDispatchEntry>(mapping.SubclassPairs.Count);
        foreach (var sp in mapping.SubclassPairs)
        {
            // suffixMap 查键 = SuffixKey 同式（SourceType.FullName + 分隔 + TargetType.FullName）
            var key = sp.SourceType.FullName + "\u0001" + sp.TargetType.FullName;
            if (!generatableKeys.Contains(key)) continue; // 落空/抑制/互指防线（F48/F11 已在各自层报）
            var suffix = suffixMap.TryGetValue(key, out var s) ? s : "";
            var srcName = sp.SourceClassName + suffix;
            var tgtName = sp.TargetClassName + suffix;
            chain.Add(new SubclassDispatchEntry(
                sp.SourceType.FullName,
                sp.TargetType.FullName,
                $"Map_{srcName}_To_{tgtName}",
                $"Map_{srcName}_To_{tgtName}_Update"));
        }
        return chain.Count == 0 ? null : chain;
    }

    /// <summary>
    /// 构建 类型 → "类名+后缀" 映射表 — 从 GenerateMapperCode 拆分
    /// <para>用于 DeepCopy 方法名和嵌套映射引用</para>
    /// <para>internal 化供 GenerationPreparation.Prepare 上提调用（逻辑逐行不动）。</para>
    /// </summary>
    /// <param name="mappings">映射快照集合</param>
    /// <returns>类型到"类名+后缀"的映射表</returns>
    internal static Dictionary<TypeRef, string> BuildTypeNameMap(System.Collections.Immutable.ImmutableArray<MappingSnapshot?> mappings, Dictionary<string, string> suffixMap)
    {
        // 镜像符号版：ClassName + MethodSuffix（DeepCopy/嵌套引用方法名带冲突后缀）
        var typeNameMap = new Dictionary<TypeRef, string>();
        foreach (var mapping in mappings)
        {
            if (mapping == null) continue;
            var suffix = GetSuffix(suffixMap, mapping);
            var srcName = mapping.SourceClassName + suffix;
            var tgtName = mapping.TargetClassName + suffix;
            if (!typeNameMap.ContainsKey(mapping.SourceType))
                typeNameMap[mapping.SourceType] = srcName;
            if (!typeNameMap.ContainsKey(mapping.TargetType))
                typeNameMap[mapping.TargetType] = tgtName;
        }
        return typeNameMap;
    }

    /// <summary>
    /// 生成模块初始化器 — 注册所有源生成器方法到 Mapper — 从 GenerateMapperCode 拆分
    /// <para>deepCopyTypes/deepCopyShapes 两参合一为 deepCopyGraphs（准备段产物，
    /// TypeName/Shape 随图携带——注册行消费点改造）。</para>
    /// </summary>
    /// <param name="sb">字符串构建器</param>
    /// <param name="mappings">映射快照集合</param>
    /// <param name="deepCopyGraphs">深拷贝图分类产物（prep.DeepCopyGraphs——注册行输出 acyclic 字面量， T5）</param>
    /// <param name="globalConfig">全局映射配置快照（合并后；null/空配置不输出快照行）</param>
    /// <param name="mutualPairs">互指有向对字典（null 表示无互指检测）</param>
    /// <param name="suffixMap">方法后缀表（输出期查表）</param>
    private static void GenerateModuleInitializer(StringBuilder sb, System.Collections.Immutable.ImmutableArray<MappingSnapshot?> mappings, Dictionary<TypeRef, (string TypeName, DeepCopyNodeShape Node, DeepCopyGraphShape Shape, IReadOnlyList<UnknownEdgeSnapshot> UnknownEdges)> deepCopyGraphs, GlobalConfigSnapshot? globalConfig = null, Dictionary<TypeRef, TypeRef>? mutualPairs = null, Dictionary<string, string>? suffixMap = null, Dictionary<MappingSnapshot, MappingSnapshot?>? reverseSnapshotTable = null)
    {
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// 模块初始化器 — 模块加载时自动注册源生成器映射委托到 Mapper 统一入口");
        sb.AppendLine("    /// </summary>");

        sb.AppendLine("    internal static class GeneratedMapperInitializer");
        sb.AppendLine("    {");
        sb.AppendLine("        [System.Runtime.CompilerServices.ModuleInitializer]");

        sb.AppendLine("        internal static void Initialize()");
        sb.AppendLine("        {");

        // 全局配置快照注册：配置非空时先注册快照（供冲突检测产出程序集清单），
        // 程序集名取首个映射类型的所在程序集（= 消费者程序集）
        if (globalConfig != null && !globalConfig.IsEmpty)
        {
            var assemblyName = mappings
                .Select(m => m?.SourceType?.AssemblyName)
                .FirstOrDefault(n => !string.IsNullOrEmpty(n)) ?? "NCMapper.Generated";
            AppendRegisterGeneratedConfig(sb, globalConfig, assemblyName);
        }

        foreach (var mapping in mappings)
        {
            if (mapping == null) continue;
            // NCMAP011：non-public 类型跳过模块初始化器注册（引用 non-public 类型会 CS0122，
            // 且 GeneratedMapper 中无对应方法可注册）
            if (mapping.SkipCodeGeneration) continue;
            // 互指对不注册（该对不生成方法，注册引用会 CS0121 二义性）
            if (mutualPairs != null && IsMutualPair(mapping, mutualPairs)) continue;
            var sourceName = mapping.SourceType.FullName;
            var targetName = mapping.TargetType.FullName;

            var coreMethodName = GetMethodName(mapping, "Map", suffixMap);
            var actionMethodName = $"{coreMethodName}_WithAction";
            var updateMethodName = $"{coreMethodName}_Update";
            var listMethodName = GetMethodName(mapping, "MapList", suffixMap);
            var listIntoMethodName = GetMethodName(mapping, "MapListInto", suffixMap);

            sb.AppendLine($"            NCMapper.Mapper.RegisterGeneratedCore<{sourceName}, {targetName}>(GeneratedMapper.{coreMethodName});");
            sb.AppendLine($"            NCMapper.Mapper.RegisterGenerated<{sourceName}, {targetName}>(GeneratedMapper.{actionMethodName});");
            sb.AppendLine($"            NCMapper.Mapper.RegisterGeneratedUpdate<{sourceName}, {targetName}>(GeneratedMapper.{updateMethodName});");
            sb.AppendLine($"            NCMapper.Mapper.RegisterGeneratedList<{sourceName}, {targetName}>(GeneratedMapper.{listMethodName});");
            // 注册批量就地映射委托（仅正向；反向区不注册，设计）
            sb.AppendLine($"            NCMapper.Mapper.RegisterGeneratedListInto<{sourceName}, {targetName}>(GeneratedMapper.{listIntoMethodName});");

            // 有 Compose 跨表字段 → 注册 Compose 委托
            if (mapping.ComposeMappings.Count > 0)
            {
                var methodSuffix = GetSuffix(suffixMap!, mapping);
                var composeMethodName = $"Compose_{mapping.TargetClassName}{methodSuffix}";
                sb.AppendLine($"            NCMapper.Mapper.RegisterGeneratedCompose<{targetName}>(GeneratedMapper.{composeMethodName});");
            }

            // 注册消费唯一构造点表内快照（同一实例防 .1——L509 注册路径点名防护；
            // 反向诊断已在构造点发射，此处不重复收集）
            var reverseMapping = reverseSnapshotTable != null && reverseSnapshotTable.TryGetValue(mapping, out var rev)
                ? rev
                : null;
            if (reverseMapping != null)
            {
                var revCoreMethodName = GetMethodName(reverseMapping, "Map", suffixMap);
                var revActionMethodName = $"{revCoreMethodName}_WithAction";
                var revUpdateMethodName = $"{revCoreMethodName}_Update";
                var revListMethodName = GetMethodName(reverseMapping, "MapList", suffixMap);
                sb.AppendLine($"            NCMapper.Mapper.RegisterGeneratedCore<{targetName}, {sourceName}>(GeneratedMapper.{revCoreMethodName});");
                sb.AppendLine($"            NCMapper.Mapper.RegisterGenerated<{targetName}, {sourceName}>(GeneratedMapper.{revActionMethodName});");
                sb.AppendLine($"            NCMapper.Mapper.RegisterGeneratedUpdate<{targetName}, {sourceName}>(GeneratedMapper.{revUpdateMethodName});");
                sb.AppendLine($"            NCMapper.Mapper.RegisterGeneratedList<{targetName}, {sourceName}>(GeneratedMapper.{revListMethodName});");
            }
        }

        // 注册 DeepCopy 委托（去重后的唯一类型） // 三参重载携带 acyclic 字面量
        // 分类为 Acyclic 的类型在层 1 走零检测快路径（IsAcyclic 分支跳过 CycleCache）；
        // Cyclic/Unknown 传 false，走 CycleCache 完整检测路径（两参重载等价语义，保守）。
        // 改从 prep.DeepCopyGraphs 取（TypeName/Shape 随图携带；遍历序与原 deepCopyTypes 一致）
        foreach (var kvp in deepCopyGraphs)
        {
            var typeName = kvp.Key.FullName;
            var deepCopyMethodName = $"DeepCopy_{kvp.Value.TypeName}";
            var acyclicLiteral = kvp.Value.Shape == DeepCopyGraphShape.Acyclic ? "true" : "false";
            sb.AppendLine($"            NCMapper.Mapper.RegisterGeneratedDeepCopy<{typeName}>(GeneratedMapper.{deepCopyMethodName}, acyclic: {acyclicLiteral});");
        }

        // 注册 Validate 委托（编译时验证结果）
        sb.AppendLine($"            NCMapper.Mapper.RegisterGeneratedValidate(GeneratedMapper.ValidateGenerated);");

        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

